func norm(v, def string) string {
	if v == "" {
		return def
	}
	return v
}

// Register adds the find_orphans tool to the given MCP server. Calls are
// recorded by the OSS value middleware, which is registered once on this shared
// MCP server and so observes the analyzers too.
func Register(srv *mcp.Server, store func() *facts.Store) {
	mcp.AddTool(srv, &mcp.Tool{
		Name:        "find_orphans",
		Description: toolDescription,
	}, func(_ context.Context, _ *mcp.CallToolRequest, in args) (*mcp.CallToolResult, any, error) {
		if store().Count() == 0 {
			return mcputil.ErrorResult("No facts available. Run generate_snapshot first."), nil, nil
		}

		syms, refSources := collect(store())
		opts := options{
			Mode:               norm(in.Mode, "both"),
			Kind:               in.Kind,
			Package:            in.Package,
			Repo:               in.Repo,
			Visibility:         norm(in.Visibility, "all"),
			Confidence:         in.Confidence,
			IncludeTests:       in.IncludeTests,
			IncludeEntrypoints: in.IncludeEntrypoints,
		}
		orphans := classify(syms, refSources, opts)
		sortOrphans(orphans)

		switch mcputil.ResolveOutputMode(in.OutputMode, mcputil.ModeSummary) {
		case mcputil.ModeFull, mcputil.ModeCompact:
			limit := in.Limit
			if limit <= 0 {
				limit = 200
			}
			if limit > 2000 {
				limit = 2000
			}
			total := len(orphans)
			if len(orphans) > limit {
				orphans = orphans[:limit]
			}
			if mcputil.ResolveOutputMode(in.OutputMode, mcputil.ModeSummary) == mcputil.ModeCompact {
				return mcputil.TextResult(mcputil.CapTokens(renderCompact(orphans, opts.Mode), in.MaxTokens, false)), nil, nil
			}
			return mcputil.JSONResultCapped(fullResponse{
				Orphans:  orphans,
				Total:    total,
				Returned: len(orphans),
				Mode:     opts.Mode,
				Note:     responseNote,
			}, in.MaxTokens)
		default:
			return mcputil.JSONResultCapped(
				summarize(orphans, population(syms, opts), len(syms), opts.Mode), in.MaxTokens)
		}
	})
}

// foldMemberUseIntoOwner marks a type as referenced by whoever references one of
// its members. See the call site for why.
func foldMemberUseIntoOwner(order []string, byName map[string]*symInput, refSources refIndex) {
	for _, name := range order {
		m := byName[name]
		if m == nil {
			continue
		}
		dot := strings.LastIndex(name, ".")
		if dot <= 0 {
			continue
		}
		owner := name[:dot]
		o, ok := byName[owner]
		if !ok || !isOwnerTypeKind(o.Kind) {
			continue
		}
		for _, cand := range candidateNames(m.Name, m.Kind) {
			for _, src := range refSources.sources(cand) {
				// External use only. A member referencing its own type, the type
				// referencing itself, or a SIBLING member of the same type, is all
				// internal: a class whose members only call each other is dead as a
				// unit, and crediting the sibling would make it immortal.
				if src == m.Name || src == owner || ownerOf(src) == owner {
					continue
				}
				addRef(refSources, owner, src)
				if seg := lastSeg(owner); seg != owner {
					addRef(refSources, seg, src)
				}
			}
		}
	}
}

// ownerOf returns a symbol's declaring type, or "" when it has none.
func ownerOf(name string) string {
	if dot := strings.LastIndex(name, "."); dot > 0 {
		return name[:dot]
	}
	return ""
}

// isOwnerTypeKind reports whether a kind can OWN members whose use implies its
// own. Deliberately the type kinds only: a method nested under another method is
// a local function, and its use says nothing about the outer one.
func isOwnerTypeKind(kind string) bool {
	switch kind {
	case facts.SymbolClass, facts.SymbolStruct, facts.SymbolInterface, facts.SymbolType:
		return true
	}
	return false
}

// Summary is the dead-code block `enola --explain` prints: the headline counts,
// split by confidence tier and, orthogonally, by class and visibility.
type Summary struct {
	// Total is the number of orphans; Candidates is the population they were drawn
	// from, which is the set the tool actually examines rather than every symbol in
	// the snapshot. Printing the latter as the denominator overstated the rate by
	// counting test and entry-point symbols orphan analysis never looks at.
	Total      int
	Candidates int
	// The confidence tiers partition the set.
	High, Medium, Low int
	// These two pairs re-cut the SAME set rather than adding to it.
	Isolated, Unreferenced int
	Exported               int
}

// Summarize counts orphans over the whole store with the find_orphans tool's own
// defaults (both classes, all kinds and visibility), so the two agree.
func Summarize(store *facts.Store) Summary {
	syms, refSources := collect(store)
	opts := options{Mode: "both", Visibility: "all"}

	s := Summary{Candidates: population(syms, opts)}
	for _, o := range classify(syms, refSources, opts) {
		s.Total++
		if o.Class == classIsolated {
			s.Isolated++
		} else {
			s.Unreferenced++
		}
		switch o.Confidence {
		case confHigh:
			s.High++
		case confMedium:
			s.Medium++
		default:
			s.Low++
		}
		if o.Exported {
			s.Exported++
		}
	}
	return s
}
