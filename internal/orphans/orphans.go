// isTestPath reports whether a repo-relative file path is test or test-support
// code (test trees, and the mocks/fixtures/helpers that exist only to serve them).
// This matters because test files are excluded from the snapshot by config ignore,
// so the tests that consume a mock or helper aren't in the graph — without the
// exclusion, such test-support code is mis-reported as dead because its only
// callers are invisible.
//
// The rule itself lives in the OSS module (facts.IsTestPath). It used to be a local
// copy, one of three that had drifted apart in both directions — this one was
// missing `Tests`/`Mocks`/`__tests__` (1959 false orphans on nan/nebenan-iOS, 34.5%
// of every orphan the repo reported) while perf's copy was missing the Gradle/KMP
// source sets, and the OSS god-class/hotspots explainers had no path check at all.
//
// Two of this copy's own rules were fixed/28 defects and did NOT survive the merge:
// `strings.Contains(p, "_test.")` claimed the production ActiveJob
// `finish_kindness_reminder_ab_test.rb`, and an unqualified `test_` prefix claimed
// `app/jobs/test_job.rb` and superset's `superset/cli/test_db.py`. Real Ruby and
// Python tests live in a `spec/`/`test/`/`tests/` tree, which the segment rules
// already claim, so those two rules only ever removed production code from the
// analysis. See internal/facts/testpath.go for the measurements.
func isTestPath(p string) bool { return facts.IsTestPath(p) }

// isDunder reports whether a bare name is a Python dunder (e.g. "__init__",
// "__enter__"). Dunders are invoked implicitly by the runtime, never referenced
// by name, so they must not be reported as orphans.
func isDunder(bareName string) bool {
	return len(bareName) > 4 &&
		strings.HasPrefix(bareName, "__") && strings.HasSuffix(bareName, "__")
}

// lastSeg returns the substring after the final name separator ('.' or '#').
// "json.NewDecoder" → "NewDecoder"; "handleError" → "handleError";
// "PostsController#markdown_id" → "markdown_id" (Ruby instance methods).
func lastSeg(s string) string {
	if i := strings.LastIndexAny(s, ".#"); i >= 0 {
		return s[i+1:]
	}
	return s
}

// candidateNames returns the short forms a symbol may be referenced by. The
// canonical name has the form "<pkg/dir>.<Sym>" or "<pkg/dir>.<Recv>.<Method>";
// the package directory uses '/' separators and attaches the symbol with '.'.
// Ruby instance methods use '#' as the receiver/method separator
// ("PostsController#markdown_id"), so both '.' and '#' are treated as name
// separators. Methods yield {Method, Recv.Method}; everything else yields {Sym}.
func candidateNames(name, kind string) []string {
	tail := name
	if i := strings.LastIndex(tail, "/"); i >= 0 {
		tail = tail[i+1:]
	}
	parts := strings.FieldsFunc(tail, func(r rune) bool { return r == '.' || r == '#' })
	n := len(parts)
	if n == 0 {
		return nil
	}
	// Strip a leading "::" — a top-level reopened class is named "::Post" but is
	// referenced as the bare "Post".
	final := strings.TrimPrefix(parts[n-1], "::")
	if final == "" {
		return nil
	}
	var out []string
	if kind == facts.SymbolMethod && n >= 2 {
		out = []string{final, strings.TrimPrefix(parts[n-2], "::") + "." + final}
	} else {
		out = []string{final}
	}
	// Ruby constants nest with "::"; a reference from inside the enclosing module
	// uses the short (last) segment, so match "AdPlugin::HouseAdSerializer" against
	// a bare "HouseAdSerializer" too. Other languages carry no "::", so this is a
	// no-op for them.
	if i := strings.LastIndex(final, "::"); i >= 0 {
		if seg := final[i+2:]; seg != "" {
			out = append(out, seg)
		}
	}
	// Ruby setters: `def foo=` yields the symbol "…foo=", but a call site `x.foo = v`
	// records the method as "foo" (no "="). Match the setter against that bare form
	// (and the "Recv.foo" form) so a setter used only via assignment is not mis-reported
	// as dead. Conservative: this only ADDS candidates, so it can never create a false
	// orphan (worst case, a getter call also keeps the same-named setter alive).
	if base, ok := strings.CutSuffix(final, "="); ok && base != "" {
		out = append(out, base)
		if kind == facts.SymbolMethod && n >= 2 {
			out = append(out, strings.TrimPrefix(parts[n-2], "::")+"."+base)
		}
	}
	return out
}

// bareName returns a symbol's unqualified name (its final '.'-segment).
func bareName(name string) string { return lastSeg(name) }

// referencedByOther reports whether any source other than the symbol itself
// references one of the symbol's short forms. Self-references (e.g. recursion)
// do not count as use.
func referencedByOther(sym symInput, refSources refIndex) bool {
	for _, cand := range candidateNames(sym.Name, sym.Kind) {
		if refSources[cand].referenced(sym.Name) {
			return true
		}
	}
	return false
}

// isDataMemberKind reports whether a kind is a data member (struct/union field,
// package-level variable or constant). Their usage — field reads and variable
// references — is never emitted as a graph edge by any extractor, so every one
// would be flagged as an orphan (a ~100% false-positive rate that, on large C
// codebases like the Linux kernel, swamps the real dead-code signal with hundreds
// of thousands of struct fields). They are excluded from the default analysis but
// remain reachable via an explicit kind= filter.
func isDataMemberKind(kind string) bool {
	return kind == facts.SymbolVariable || kind == facts.SymbolConstant
}

// frameworkLoadedSegments mark directory trees that are not shippable application
// code we would ever flag as dead. Their symbols are unreferenced-by-name by
// construction, so each would be a false positive — pure noise in the aggregate,
// exactly like test trees:
//   - migrate / post_migrate: Rails migrations, run once by ActiveRecord by
//     filename and never referenced by name (the single largest dead-code-noise
//     bucket on a Rails app like Discourse — thousands of one-shot classes).
//   - script: standalone scripts / one-off entry points, invoked directly.
//   - vendor: vendored third-party code, not ours to clean up (and only partially
//     covered by the OSS generated-path filter).
//
// They are dropped from the default analysis but stay reachable via an explicit
// package= filter (mirrors the data-member kind= opt-in).
var frameworkLoadedSegments = map[string]bool{
	"migrate": true, "post_migrate": true, // Rails db/migrate, db/post_migrate
	"script": true, "scripts": true,
	"vendor": true,
}

// isFrameworkLoadedPath reports whether a repo-relative file path is in a
// framework-loaded / non-app tree (see frameworkLoadedSegments).
func isFrameworkLoadedPath(p string) bool {
	for _, part := range strings.Split(p, "/") {
		if frameworkLoadedSegments[part] {
			return true
		}
	}
	return false
}

// isScopePseudoSymbol reports whether a symbol name is a Rails model `scope:<name>`
// pseudo-symbol. The Ruby extractor emits each `scope :foo` as a receiver-less
// `scope:foo` symbol, but scopes are invoked via dynamic class-method dispatch
// (Model.foo, chained), never by that literal name — so, like dunders, they can
// never match a reference and would always be (falsely) reported, polluting the
// high-confidence bucket. Excluded unconditionally.
func isScopePseudoSymbol(name string) bool {
	return strings.HasPrefix(name, "scope:")
}

// rubyImplicitHooks are Ruby class/module/object lifecycle callbacks invoked
// implicitly by the runtime (never by an explicit by-name call): the interpreter
// calls `inherited` when a class is subclassed, `included`/`extended`/`prepended`
// when a module is mixed in, `method_missing`/`respond_to_missing?` on dispatch,
// `initialize` via `.new`, and so on. Like Python dunders they can never match a
// reference and would always be (falsely) reported. Excluded for Ruby symbols.
var rubyImplicitHooks = map[string]bool{
	"inherited": true, "included": true, "extended": true, "prepended": true,
	"method_missing": true, "respond_to_missing?": true,
	"method_added": true, "method_removed": true, "method_undefined": true,
	"singleton_method_added": true, "singleton_method_removed": true, "singleton_method_undefined": true,
	"const_missing": true, "append_features": true, "prepend_features": true, "extend_object": true,
	"initialize": true, "initialize_copy": true, "initialize_dup": true, "initialize_clone": true,
	"coerce": true, "to_proc": true,
}

// rubyFrameworkHooks are convention methods that popular Ruby frameworks invoke by
// reflection on classes that define/override them — never by an explicit call in
// app code, so they carry no call edge and would always be (falsely) reported.
// Unlike the language-level rubyImplicitHooks these are library conventions; the
// list is intentionally curated (specific, low-collision names) and extensible.
var rubyFrameworkHooks = map[string]bool{
	// GraphQL-Ruby: the gem calls these on schema/type/field/mutation/resolver classes.
	"authorized?": true, "authorizes_object?": true,
	"unauthorized_object": true, "unauthorized_field": true,
	"visible?": true, "accessible?": true,
	"coerce_input": true, "coerce_result": true, "scope_items": true,
	// ActionCable channels.
	"subscribed": true, "unsubscribed": true,
	// Rails AbstractController reflection.
	"action_methods": true,
	// Rails ActiveRecord single-table-inheritance reflection (invoked by the ORM).
	"find_sti_class": true, "sti_class_for": true, "sti_name": true,
	"polymorphic_name": true, "discriminate_class_for_record": true,
}

// isRubyImplicitHook reports whether a Ruby (.rb) symbol's bare name is a runtime
// lifecycle hook (rubyImplicitHooks) or a framework-invoked convention method
// (rubyFrameworkHooks). Gated on the file extension so identically named methods in
// other languages are unaffected.
func isRubyImplicitHook(file, bareName string) bool {
	return strings.HasSuffix(file, ".rb") && (rubyImplicitHooks[bareName] || rubyFrameworkHooks[bareName])
}

// constReceiverRefs returns the constant-receiver short forms implied by a
// "Recv.method" usage target. Extractors record a call on a constant as
// "Foo.bar" / "Ns::Class.method"; the receiver constant ("Foo", "Ns::Class") is
// itself used, but that use never appears as a standalone edge — so a class
// referenced only as a call receiver (e.g. Ruby `PostCreator.create`, with no
// instantiates edge) looks unreferenced. We fold the receiver in as a use. Only
// uppercase-initial receivers (constants/types) qualify, so lowercase variable
// receivers and package qualifiers (Go `json.NewDecoder`) are not mistaken for a
// class reference. This only ever ADDS references, so it can never turn live code
// into a false orphan — consistent with the package's conservative bias.
func constReceiverRefs(target string) []string {
	i := strings.LastIndex(target, ".")
	if i <= 0 {
		return nil
	}
	recv := target[:i]
	if r := rune(recv[0]); r < 'A' || r > 'Z' {
		return nil
	}
	out := []string{recv}
	if j := strings.LastIndex(recv, "::"); j >= 0 {
		if tail := recv[j+2:]; tail != "" {
			out = append(out, tail)
		}
	}
	return out
}

// selfReceiverRefs returns the bare method name implied by a self-qualified usage
// target. Extractors normally reduce same-object dispatch to a bare method name,
// but as a defense in depth (across languages) we also fold any target shaped
// `self.X`, `self.class.X`, `cls.X`, `this.X`, or `self::X` down to `X` — so a
// method reached only via such a dynamic self-dispatch is not mis-reported as an
// unreferenced orphan. Like constReceiverRefs this only ever ADDS references, so
// it can never turn live code into a false orphan.
func selfReceiverRefs(target string) []string {
	var recv, method string
	if i := strings.LastIndex(target, "."); i > 0 && i < len(target)-1 {
		recv, method = target[:i], target[i+1:]
	} else if i := strings.LastIndex(target, "::"); i > 0 && i < len(target)-2 {
		recv, method = target[:i], target[i+2:]
	} else {
		return nil
	}
	switch recv {
	case "self", "self.class", "self.singleton_class", "cls", "this", "klass":
		return []string{method}
	}
	return nil
}

// androidEntryPointComponents are Android component roles instantiated by the
// framework/runtime (via the manifest, the Compose runtime, WorkManager, or a
// ViewModelProvider) rather than by app code — so they have no incoming call edge
// by construction and must not be reported as orphans, like main/init. Roles that
// ARE ordinary app classes reached through DI (repository, usecase, di_module) are
// deliberately omitted so a genuinely dead one is still surfaced.
var androidEntryPointComponents = map[string]bool{
	"application": true, "activity": true, "fragment": true, "service": true,
	"broadcast_receiver": true, "content_provider": true, "worker": true,
	"composable": true, "viewmodel": true,
}

// iosEntryPointComponents are iOS component roles instantiated by the SwiftUI
// runtime rather than by app code, so they have no incoming call edge by
// construction — like main/init. The Android set above is deliberately NOT
// mirrored: app code constructs a SwiftUI View from its parent's body, a ViewModel
// via @StateObject, and a UIViewController from a coordinator, and those edges ARE
// tracked, so an unreferenced one is real dead code. Measured across
// my-golf-journal-ios and nebenan-iOS: 0 of 25 viewcontroller symbols are orphans,
// and each of the 6 uiview orphans is genuinely unused — rescuing either role would
// suppress real findings to fix nothing.
var iosEntryPointComponents = map[string]bool{
	"swiftui_app": true,
}

// isExcluded reports whether a symbol is dropped before orphan analysis given
// the test/entry-point options.
func isExcluded(sym symInput, opts options) bool {
	bn := bareName(sym.Name)
	// Dunders (__init__, __enter__, …) are invoked implicitly, never by name.
	if isDunder(bn) {
		return true
	}
	// Rails model scopes are dynamic-dispatch pseudo-symbols, never referenced by
	// the literal `scope:<name>` — always noise, like dunders.
	if isScopePseudoSymbol(sym.Name) {
		return true
	}
	// Ruby lifecycle hooks (inherited/included/method_missing/initialize/…) are
	// invoked by the runtime, never by name — always noise, like dunders.
	if isRubyImplicitHook(sym.File, bn) {
		return true
	}
	// Data members have no edge-tracked usage, so they are pure noise in the
	// aggregate view. Drop them unless the caller explicitly asks for that kind.
	if opts.Kind == "" && isDataMemberKind(sym.Kind) {
		return true
	}
	// Framework-loaded / non-app trees (Rails migrations, script/, vendor/) are
	// unreferenced-by-name by construction. Drop them unless the caller has scoped
	// the query to a package (the explicit opt-in to inspect such a tree).
	if opts.Package == "" && isFrameworkLoadedPath(sym.File) {
		return true
	}
	// TS/JS CLI-task trees (e.g. `tasks/`) are dispatched by dynamic-string require
	// (`require(`./tasks/${name}`)`) from a runner, so their entry functions have no
	// resolvable caller — like script/ above. Language-gated so a Go `internal/tasks`
	// package is unaffected; opt back in with package=.
	if opts.Package == "" && isTSLang(sym.Language) && isTSDynamicEntryPath(sym.File) {
		return true
	}
	// Python documentation trees (docs/ — Sphinx conf.py, diagram generators) are
	// run by the docs toolchain, never imported by the app, so their functions have
	// no caller by construction. Language-gated so a non-Python `docs` package is
	// unaffected; opt back in with package=.
	if opts.Package == "" && isPyLang(sym.Language) && isPyNonAppPath(sym.File) {
		return true
	}
	// Codegen output (file carries a "DO NOT EDIT"/"generated by" banner). A
	// generator emits a whole API surface regardless of how much the project calls,
	// so its unreferenced half is guaranteed noise: deleting it does not clean
	// anything up, it just gets regenerated. Language-agnostic — the banner is the
	// signal — and reachable with package= like the trees above.
	if opts.Package == "" && sym.Generated {
		return true
	}
	if !opts.IncludeTests {
		if isTestPath(sym.File) {
			return true
		}
		// Go test/benchmark/example/fuzz entry points and pytest test_* functions.
		if strings.HasPrefix(bn, "Test") || strings.HasPrefix(bn, "Benchmark") ||
			strings.HasPrefix(bn, "Example") || strings.HasPrefix(bn, "Fuzz") ||
			strings.HasPrefix(bn, "test_") {
			return true
		}
	}
	if !opts.IncludeEntrypoints {
		if bn == "main" || bn == "init" {
			return true
		}
		// Framework/DI entry points (Kotlin `override` callbacks — Android lifecycle,
		// interface implementations — Dagger/Hilt @Provides/@Binds methods,
		// manifest/runtime-instantiated Android components: Activities, Fragments,
		// Services, Workers, Composables, …, and the @main SwiftUI App) are dispatched
		// by the runtime/container, never referenced by their own literal name, so they
		// have no incoming call edge by construction. Like main/init, they are not dead
		// code; treat them as entry points and drop them unless the caller opts in.
		// (An override also cannot be deleted in isolation.)
		if sym.Override || sym.DIProvider || androidEntryPointComponents[sym.AndroidComponent] ||
			iosEntryPointComponents[sym.IOSComponent] {
			return true
		}
		// JVM framework-instantiated classes: a Spring stereotype (@Component/@Service/
		// @Configuration/… — a non-empty `component` role) is wired by the Spring
		// container via classpath scanning, and a Dubbo @Activate SPI extension is
		// instantiated by name by the ExtensionLoader from a META-INF/dubbo service
		// file. Neither is referenced by its own name in code, so an unreferenced one
		// has no incoming edge by construction — an entry point, not dead code. (A
		// genuinely-dead bean — defined but never scanned — is thereby also hidden;
		// that is the standard entry-point tradeoff, matching the Android/iOS/route
		// cases above. The untagged plain-SPI impls — registered only in a service
		// file, no @Activate — carry neither prop and are still reported.)
		if sym.SpringComponent != "" || sym.DubboActivate || sym.ScannedPlugin {
			return true
		}
		// Next.js App-Router route handlers (GET/POST/… exports in a route.ts) are
		// invoked by the framework for a matching request, never referenced by name —
		// an entry point like main, not dead code. React components/hooks are NOT
		// excluded here: a genuinely-unreferenced component IS dead code we want
		// surfaced (just at a lower, verify-first confidence — see confidenceFor).
		if sym.WebComponent == "route_handler" {
			return true
		}
		// React class-component lifecycle methods (render, componentDidMount, …) are
		// called by React itself, never by name, so they have no incoming call edge by
		// construction — like Android lifecycle overrides. They dominate the TS/JS
		// method-orphan noise; treat them as framework entry points and drop them
		// unless the caller opts in.
		if sym.Kind == facts.SymbolMethod && isTSLang(sym.Language) && reactLifecycleMethods[bn] {
			return true
		}
		// Python framework hooks (gunicorn server hooks, ASGI lifespan, Airflow
		// cluster policies / settings hooks) are dispatched by name from config or a
		// settings module, never by a static call — entry points, not dead code.
		if isPyLang(sym.Language) && pyFrameworkHookNames[bn] {
			return true
		}
		// click/Typer CLI commands are registered with and dispatched by the CLI
		// framework, never called by name — entry points like main.
		if sym.CLICommand {
			return true
		}
		// Decorator-registered handlers (FastAPI exception handlers/middleware/event
		// hooks, Modal remote functions) are invoked by the framework on a matching
		// event, never by a static call — the same case as the CLI commands above.
		if sym.FrameworkReg {
			return true
		}
	}
	return false
}

