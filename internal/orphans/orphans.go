// confidenceFor returns the confidence tier for a symbol. Only plain functions have
// their incoming usage reliably captured by the call graph (high). Methods are
// frequently reached as method values, via interface dispatch, or by reflection —
// none of which are edges — and type usage (field/param/return) is not edge-tracked
// either, so every other kind is low.
func confidenceFor(sym symInput) string {
	name, kind := sym.Name, sym.Kind
	// Operator overloads (Swift `func +`, `func <-`; Ruby `def +`) are invoked via
	// operator syntax, which is largely NOT tracked as a call edge (only custom
	// operators are, in Swift), so an unreferenced one is a lead to verify — never
	// the high-confidence "safest to remove first" tier a plain function would get.
	if isOperatorName(name) {
		return confLow
	}
	// TS/JS usage is only partially edge-tracked: components render via JSX, pages are
	// wired by data-driven route tables, and dynamic import()/require() and string
	// dispatch have no edge. We DO now synthesize file-scope reference edges for those
	// (see the TS extractor's KindFileRef pass), but the coverage is heuristic, so a
	// TS/JS orphan is a lead to verify, never the "safe to delete" high tier a Go/Rust
	// call-graph orphan earns. React components/hooks (web_component set) are the most
	// dynamically-reached, so they drop a further tier.
	if isTSLang(sym.Language) {
		if sym.WebComponent != "" {
			return confLow
		}
		if kind == facts.SymbolFunc {
			return confMedium
		}
		return confLow
	}
	switch kind {
	case facts.SymbolFunc:
		return confHigh
	case facts.SymbolStruct, facts.SymbolClass, facts.SymbolInterface:
		// Types are marked used via instantiates/injects/implements edges, which
		// ARE tracked — so an unreferenced type is a strong dead-code lead. Not
		// high, because field/param/return type usage is not edge-tracked.
		return confMedium
	default:
		return confLow // method, type, const, var
	}
}

// isTSLang reports whether a symbol's language is TypeScript/JavaScript. The TS
// extractor labels both TS and JS facts "typescript".
func isTSLang(lang string) bool {
	switch lang {
	case "typescript", "javascript":
		return true
	}
	return false
}

// isOperatorName reports whether the symbol's short name is an operator (e.g. "+",
// "<-", "^=") rather than an identifier — i.e. its first rune is neither a letter
// nor an underscore.
func isOperatorName(name string) bool {
	seg := lastSeg(name)
	if seg == "" {
		return false
	}
	r := []rune(seg)[0]
	return !unicode.IsLetter(r) && r != '_'
}

// passesFilters applies the kind/package/repo/visibility filters.
func passesFilters(sym symInput, opts options) bool {
	if opts.Kind != "" && sym.Kind != opts.Kind {
		return false
	}
	if opts.Package != "" && !strings.Contains(sym.Package, opts.Package) {
		return false
	}
	if opts.Repo != "" && sym.Repo != opts.Repo {
		return false
	}
	switch opts.Visibility {
	case "exported":
		if !sym.Exported {
			return false
		}
	case "unexported":
		if sym.Exported {
			return false
		}
	}
	switch opts.Confidence {
	case confHigh:
		if confidenceFor(sym) != confHigh {
			return false
		}
	case confMedium:
		if confidenceFor(sym) != confMedium {
			return false
		}
	case confLow:
		if confidenceFor(sym) != confLow {
			return false
		}
	}
	return true
}

// classify is the pure orphan core. Given the symbols, the reference index, and
// resolved options, it returns the orphans matching the requested mode/filters.
// isCandidate reports whether orphan analysis considered this symbol at all: it was
// not excluded (test code, entry points, framework-loaded paths) and it passed the
// caller's filters. This is the ONE admission gate — classify() and population()
// both go through it, so the set of orphans and the population they were drawn from
// can never disagree. Two hand-copied admission tests is precisely how orphans and
// perf drifted apart (see facts.IsTestPath).
//
// It is also the denominator of every rate this tool reports. It used to be
// implicit, and the handler passed len(syms) — every symbol in the snapshot,
// including the test and entry-point symbols that can never be orphans — so the
// dead-code rate was diluted by symbols the analyzer never looked at.
func isCandidate(sym symInput, opts options) bool {
	return !isExcluded(sym, opts) && passesFilters(sym, opts)
}

// population counts the symbols orphan analysis drew from, under the given options.
// It is the honest denominator for len(classify(...)).
func population(syms []symInput, opts options) int {
	n := 0
	for _, sym := range syms {
		if isCandidate(sym, opts) {
			n++
		}
	}
	return n
}

// A symbol is an orphan when nothing else references it; it is classed
// "isolated" when it also references nothing, else "unreferenced".
// Detect returns dead-code orphans in the store using the same collect+classify
// core as the find_orphans tool, with the tool's default options (mode=both, all
// kinds and visibility, tests and entry points excluded). It is what the package's
// own annotate pass runs to mark orphan symbols on the store.
func Detect(store *facts.Store) []Orphan {
	syms, refSources := collect(store)
	orphans := classify(syms, refSources, options{Mode: "both", Visibility: "all"})
	sortOrphans(orphans)
	return orphans
}

func classify(syms []symInput, refSources refIndex, opts options) []Orphan {
	out := make([]Orphan, 0)
	for _, sym := range syms {
		if sym.Claimed {
			continue // dead-methods already reports it; see symInput.Claimed
		}
		if !isCandidate(sym, opts) {
			continue
		}
		if referencedByOther(sym, refSources) {
			continue // referenced → not an orphan
		}
		class := classUnreferenced
		if !sym.UsageOut {
			class = classIsolated
		}
		switch opts.Mode {
		case classIsolated:
			if class != classIsolated {
				continue
			}
		case classUnreferenced:
			if class != classUnreferenced {
				continue
			}
		}
		o := Orphan{
			Name:       sym.Name,
			Kind:       sym.Kind,
			Class:      class,
			Confidence: confidenceFor(sym),
			Package:    sym.Package,
			File:       sym.File,
			Line:       sym.Line,
			Repo:       sym.Repo,
			Exported:   sym.Exported,
		}
		if sym.Exported {
			o.Note = "exported — may be used outside this snapshot; verify before removal"
		}
		out = append(out, o)
	}
	return out
}

// sortOrphans orders orphans by package then name for deterministic output.
func sortOrphans(o []Orphan) {
	sort.SliceStable(o, func(i, j int) bool {
		if o[i].Package != o[j].Package {
			return o[i].Package < o[j].Package
		}
		return o[i].Name < o[j].Name
	})
}

// collect reads the fact store via the public bootstrap API and produces the
// classifier inputs: the per-symbol records and the short-name reference index.
// It never names a facts.* type (module boundary).
func collect(store *facts.Store) ([]symInput, refIndex) {
	claimed := deadmethods.ClaimedSymbols(store)
	symbols := store.ByKind(facts.KindSymbol)
	// References are matched by name (see responseNote), so a symbol's identity is
	// its name. Snapshots can carry several facts for one name (re-exports, the
	// same relative path across repos, extractor quirks); collapse them into one
	// record — UsageOut is OR-ed across copies — so a name is reported at most once
	// and classified consistently rather than as both isolated and unreferenced.
	byName := make(map[string]*symInput, len(symbols))
	order := make([]string, 0, len(symbols))
	refSources := make(refIndex)

	for _, f := range symbols {
		if mcputil.IsGeneratedPath(f.File) {
			continue // build/generated artifact — never a real source orphan
		}
		si := byName[f.Name]
		if si == nil {
			_, isClaimed := claimed[f.Name]
			si = &symInput{Name: f.Name, File: f.File, Line: f.Line, Repo: f.Repo, Claimed: isClaimed}
			byName[f.Name] = si
			order = append(order, f.Name)
		}
		if si.Kind == "" {
			if sk, ok := f.PropAny(propSymbolKind).(string); ok {
				si.Kind = sk
			}
		}
		if exp, ok := f.PropAny(propExported).(bool); ok && exp {
			si.Exported = true
		}
		if ov, ok := f.PropAny(propOverride).(bool); ok && ov {
			si.Override = true
		}
		if di, ok := f.PropAny(propDIProvider).(bool); ok && di {
			si.DIProvider = true
		}
		if ac, ok := f.PropAny(propAndroidComponent).(string); ok && si.AndroidComponent == "" {
			si.AndroidComponent = ac
		}
		if ic, ok := f.PropAny(propIOSComponent).(string); ok && si.IOSComponent == "" {
			si.IOSComponent = ic
		}
		if wc, ok := f.PropAny(propWebComponent).(string); ok && si.WebComponent == "" {
			si.WebComponent = wc
		}
		if lang, ok := f.PropAny(propLanguage).(string); ok && si.Language == "" {
			si.Language = lang
		}
		if cc, ok := f.PropAny(propCLICommand).(bool); ok && cc {
			si.CLICommand = true
		}
		if fr, ok := f.PropAny(propFrameworkRegistered).(bool); ok && fr {
			si.FrameworkReg = true
		}
		if g, ok := f.PropAny(propGenerated).(bool); ok && g {
			si.Generated = true
		}
		if sc, ok := f.PropAny(propSpringComponent).(string); ok && si.SpringComponent == "" {
			si.SpringComponent = sc
		}
		if da, ok := f.PropAny(propDubboActivate).(bool); ok && da {
			si.DubboActivate = true
		}
		if sp, ok := f.PropAny(propScannedPlugin).(bool); ok && sp {
			si.ScannedPlugin = true
		}
		for _, r := range f.Relations {
			switch {
			case r.Kind == facts.RelDeclares && si.Package == "":
				si.Package = r.Target
			case isUsageKind(r.Kind):
				si.UsageOut = true
				addRef(refSources, r.Target, f.Name)
				if seg := lastSeg(r.Target); seg != r.Target {
					addRef(refSources, seg, f.Name)
				}
				// Fold the constant receiver of a "Foo.bar" call in as a use of Foo,
				// so a class referenced only via a call (e.g. Ruby PostCreator.create)
				// is not mis-reported as an unreferenced orphan.
				for _, recv := range constReceiverRefs(r.Target) {
					addRef(refSources, recv, f.Name)
				}
				// Fold self-qualified dispatch (`self.class.foo`, `cls.foo`) down to
				// the bare method name, so a method reached only via dynamic
				// self-dispatch is not mis-reported as an unreferenced orphan.
				for _, m := range selfReceiverRefs(r.Target) {
					addRef(refSources, m, f.Name)
				}
			}
		}
	}

	syms := make([]symInput, 0, len(order))
	for _, name := range order {
		syms = append(syms, *byName[name])
	}

	// Package facts carry the functions a package's own var and const initializers
	// reference. A dispatch table is usually an unexported package-level var, so it
	// has no symbol of its own and the only honest owner of the edge is the package
	// — see goextractor/funcvalues.go. Without this, every parser reachable only
	// through such a table reads as dead at high confidence. Only usage relations are
	// folded in; a module's `imports` and `declares` say nothing about a symbol.
	for _, f := range store.ByKind(facts.KindModule) {
		for _, r := range f.Relations {
			if !isUsageKind(r.Kind) {
				continue
			}
			addRef(refSources, r.Target, f.Name)
			if seg := lastSeg(r.Target); seg != r.Target {
				addRef(refSources, seg, f.Name)
			}
		}
	}

	// Route facts reference their handler symbol via props["handler"] (e.g.
	// "aiCoachHandler.GetCoachingInsight"). HTTP handlers are registered as method
	// VALUES, so this usage never appears as a "calls" edge — fold it in here so
	// handler methods are not mis-reported as orphans. The route name is the
	// reference source (never equal to a symbol name).
	for _, f := range store.ByKind(facts.KindRoute) {
		h, _ := f.PropAny(propHandler).(string)
		if h == "" {
			continue
		}
		addRef(refSources, h, f.Name)
		if seg := lastSeg(h); seg != h {
			addRef(refSources, seg, f.Name)
		}
	}

	// Test-reference facts (KindTestRef) carry the production symbols a test/spec
	// file exercises. Test files are excluded from normal indexing, so these are
	// the ONLY visible evidence that a symbol is used by a test — fold them in so a
	// production method called only from a spec is not mis-reported as dead. The
	// fact name is the test file path (never equal to a production symbol name), so
	// this introduces no self-reference.
	for _, f := range store.ByKind(facts.KindTestRef) {
		for _, r := range f.Relations {
			if r.Kind != facts.RelCalls {
				continue
			}
			addRef(refSources, r.Target, f.Name)
			if seg := lastSeg(r.Target); seg != r.Target {
				addRef(refSources, seg, f.Name)
			}
			for _, recv := range constReceiverRefs(r.Target) {
				addRef(refSources, recv, f.Name)
			}
			for _, m := range selfReceiverRefs(r.Target) {
				addRef(refSources, m, f.Name)
			}
		}
	}

	// File-reference facts (KindFileRef) carry the production symbols referenced by
	// top-level / file-scope calls that have no enclosing symbol — fixtures
	// (db/fixtures/*.rb doing `Badge.foo`), initializers, and plugin
	// `after_initialize do register_x ... end` blocks. Fold them in exactly like
	// KindTestRef so those methods are not mis-reported as dead. The fact name is the
	// source file path (never equal to a symbol name), so no self-reference arises.
	for _, f := range store.ByKind(facts.KindFileRef) {
		for _, r := range f.Relations {
			if r.Kind != facts.RelCalls {
				continue
			}
			addRef(refSources, r.Target, f.Name)
			if seg := lastSeg(r.Target); seg != r.Target {
				addRef(refSources, seg, f.Name)
			}
			for _, recv := range constReceiverRefs(r.Target) {
				addRef(refSources, recv, f.Name)
			}
			for _, m := range selfReceiverRefs(r.Target) {
				addRef(refSources, m, f.Name)
			}
		}
	}

	// Module facts carry usage edges that have no enclosing symbol — notably C/C++
	// file-scope registration-macro references (module_init(foo), EXPORT_SYMBOL(foo),
	// DEVICE_ATTR(.., show, store)), which the extractor hangs off the directory
	// module fact. Fold those in so the registered entry points are not mis-reported
	// as orphans. The module name (`<dir>`) is the source — never equal to a symbol
	// name (`<dir>.<name>`), so this introduces no self-reference.
	for _, f := range store.ByKind(facts.KindModule) {
		for _, r := range f.Relations {
			if !isUsageKind(r.Kind) {
				continue
			}
			addRef(refSources, r.Target, f.Name)
			if seg := lastSeg(r.Target); seg != r.Target {
				addRef(refSources, seg, f.Name)
			}
			for _, recv := range constReceiverRefs(r.Target) {
				addRef(refSources, recv, f.Name)
			}
			for _, m := range selfReceiverRefs(r.Target) {
				addRef(refSources, m, f.Name)
			}
		}
	}

	// A TYPE whose member is used is used. The graph records a call to
	// `Extensions.AddSecretsManagerServices` as a reference to the METHOD, and
	// nothing ever names the static class that holds it — so the class read as an
	// isolated orphan while its own method was demonstrably called. The same shape
	// covers a controller reached only through its routed action.
	//
	// 578 of bitwarden-server's 1,145 orphan classes (50%) had at least one used
	// member, which made this the largest remaining false-positive bucket after DI
	// registrations were folded into the graph itself.
	//
	// The USER of the member becomes the user of the type, not the member: crediting
	// the member would make every type its own referent and no type could ever be
	// dead.
	foldMemberUseIntoOwner(order, byName, refSources)

	// Python __init__.py re-exports (`from .x import Y`) surface Y as part of the
	// package's public API. Such names are referenced via the package, not by a
	// call edge, so fold them in as references to avoid mis-reporting public
	// re-exported symbols as orphans. The dependency fact name is the source.
	for _, f := range store.ByKind(facts.KindDependency) {
		if names, ok := f.Prop(propReexports); ok {
			for _, n := range toStringSlice(names) {
				addRef(refSources, n, f.Name)
			}
		}
		// Ruby mixins (`include`/`extend`/`prepend M`) emit an `implements` edge
		// on the dependency fact, not on a symbol fact, so the mixed-in module
		// would otherwise look unreferenced. Fold those targets in as uses.
		for _, r := range f.Relations {
			if r.Kind != facts.RelImplements {
				continue
			}
			addRef(refSources, r.Target, f.Name)
			if seg := lastSeg(r.Target); seg != r.Target {
				addRef(refSources, seg, f.Name)
			}
		}
	}

	// Dynamic-dispatch prefixes: an interpolated symbol like `:"report_#{type}"`
	// implies methods named `report_*` are invoked by computed name
	// (public_send/send), which the graph cannot record as a call edge. Treat any
	// function/method whose bare name starts with such a prefix as referenced, so it
	// is not mis-reported as dead. Evidence-based (only fires when such a symbol
	// exists) and additive — it can only hide a real orphan, never invent one.
	var dynPrefixes []string
	for _, f := range store.ByKind(facts.KindFileRef) {
		if raw, ok := f.Prop(propDynamicSendPrefixes); ok {
			dynPrefixes = append(dynPrefixes, toStringSlice(raw)...)
		}
	}
	if len(dynPrefixes) > 0 {
		for i := range syms {
			if syms[i].Kind != facts.SymbolFunc && syms[i].Kind != facts.SymbolMethod {
				continue
			}
			bn := bareName(syms[i].Name)
			for _, p := range dynPrefixes {
				if p != "" && strings.HasPrefix(bn, p) {
					addRef(refSources, bn, "\x00dynamic-dispatch")
					break
				}
			}
		}
	}

	return syms, refSources
}

// addRef records that source references the given candidate name.
func addRef(refSources refIndex, name, source string) {
	refSources.add(name, source)
}

// toStringSlice coerces a fact prop into a []string. Props deserialized from a
// snapshot arrive as []any; in-memory facts may already be []string.
func toStringSlice(v any) []string {
	switch s := v.(type) {
	case []string:
		return s
	case []any:
		out := make([]string, 0, len(s))
		for _, e := range s {
			if str, ok := e.(string); ok && str != "" {
				out = append(out, str)
			}
		}
		return out
	}
	return nil
}

