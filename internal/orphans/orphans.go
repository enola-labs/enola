// summarize builds the per-symbol-type summary from the orphan list.
// summarize aggregates the orphan set. `candidates` is the population the orphans
// were drawn from (post-exclusion, post-filter) and is the denominator; `repoWide` is
// the whole snapshot, carried only as context. The argument order is the contract:
// the scoped number comes first, because that is the one every rate is built on.
func summarize(orphans []Orphan, candidates, repoWide int, mode string) summaryResponse {
	resp := summaryResponse{
		TotalSymbols:    candidates,
		RepoWideSymbols: repoWide,
		TotalOrphans:    len(orphans),
		Mode:            mode,
		Note:            responseNote,
	}
	idx := make(map[string]int)
	for _, o := range orphans {
		if o.Class == classIsolated {
			resp.Isolated++
		} else {
			resp.Unreferenced++
		}
		i, ok := idx[o.Kind]
		if !ok {
			i = len(resp.ByKind)
			idx[o.Kind] = i
			resp.ByKind = append(resp.ByKind, kindCount{Kind: o.Kind})
		}
		kc := &resp.ByKind[i]
		kc.Total++
		if o.Class == classIsolated {
			kc.Isolated++
		} else {
			kc.Unreferenced++
		}
		if o.Exported {
			kc.Exported++
		}
		switch o.Confidence {
		case confHigh:
			kc.HighConfidence++
		case confMedium:
			kc.MediumConfidence++
		}
	}
	sort.SliceStable(resp.ByKind, func(i, j int) bool {
		if resp.ByKind[i].Total != resp.ByKind[j].Total {
			return resp.ByKind[i].Total > resp.ByKind[j].Total
		}
		return resp.ByKind[i].Kind < resp.ByKind[j].Kind
	})
	return resp
}

func renderCompact(orphans []Orphan, mode string) string {
	var sb strings.Builder
	fmt.Fprintf(&sb, "Orphan symbols — %d (mode=%s):\n\n", len(orphans), mode)
	sb.WriteString("| Kind | Name | Class | Conf | Location |\n")
	sb.WriteString("|------|------|-------|------|----------|\n")
	for _, o := range orphans {
		loc := o.File
		if o.Line > 0 {
			loc = fmt.Sprintf("%s:%d", o.File, o.Line)
		}
		fmt.Fprintf(&sb, "| %s | %s | %s | %s | %s |\n", o.Kind, o.Name, o.Class, o.Confidence, loc)
	}
	return sb.String()
}

