package goextractor

import (
	"context"
	"os"
	"path/filepath"
	"slices"
	"testing"

	"github.com/enola-labs/enola/internal/facts"
)

func goModuleFacts(t *testing.T, files map[string]string) []facts.Fact {
	t.Helper()
	repo := t.TempDir()
	files["go.mod"] = "module example.com/shop\n\ngo 1.22\n"
	var rels []string
	for rel, content := range files {
		abs := filepath.Join(repo, rel)
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(abs, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
		rels = append(rels, rel)
	}
	ff, err := New().Extract(context.Background(), repo, rels)
	if err != nil {
		t.Fatal(err)
	}
	return ff
}

func usesOf(ff []facts.Fact, name string) []string {
	var out []string
	for _, f := range ff {
		if f.Kind == facts.KindSymbol && f.Name == name {
			for _, r := range f.Relations {
				if r.Kind == facts.RelInstantiates {
					out = append(out, r.Target)
				}
			}
		}
	}
	return out
}

// A type a package-level var constructs or a generic call takes as its type argument
// is used, though no function constructs it.
func TestTypeUses_PackageVarsAndTypeArguments(t *testing.T) {
	ff := goModuleFacts(t, map[string]string{
		"keys/keys.go": `package keys

type requestKey struct{}

var RequestKey = requestKey{}
`,
		"health/health.go": `package health

type status struct{ Code string }

func decode[T any](b []byte) (T, error) { var v T; return v, nil }

func Check(b []byte) (string, error) {
	s, err := decode[status](b)
	return s.Code, err
}
`,
	})
	if got := usesOf(ff, "example.com/shop/keys.RequestKey"); !slices.Contains(got, "example.com/shop/keys.requestKey") {
		t.Errorf("RequestKey uses %v, want its key type", got)
	}
	if got := usesOf(ff, "example.com/shop/health.Check"); !slices.Contains(got, "example.com/shop/health.status") {
		t.Errorf("Check uses %v, want the type argument", got)
	}
}

// A generated registry names every type it holds; that is no use of them.
func TestTypeUses_GeneratedRegistryIsNoUse(t *testing.T) {
	ff := goModuleFacts(t, map[string]string{
		"pb/types.pb.go": `// Code generated by protoc-gen-go. DO NOT EDIT.

package pb

type Ping struct{}

var fileGoTypes = []any{(*Ping)(nil)}
`,
	})
	if got := usesOf(ff, "example.com/shop/pb.fileGoTypes"); len(got) != 0 {
		t.Errorf("a generated registry recorded uses %v", got)
	}
}
