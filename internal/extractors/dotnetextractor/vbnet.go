func vbIsKeyword(s string) bool { return vbKeywords[strings.ToLower(s)] }

// vbExported reports whether a declaration line is part of the public surface.
// `Friend` is VB's `internal`, so it is not exported, matching how the C# walker
// treats `internal`.
func vbExported(line string) bool {
	l := strings.ToLower(line)
	return strings.HasPrefix(l, "public ") || strings.HasPrefix(l, "protected ")
}

// vbHasModifier reports whether a declaration carries a modifier word. A plain
// token scan rather than a compiled pattern: this runs per declaration line, and
// building a regexp each time would dominate the walk.
func vbHasModifier(line, mod string) bool {
	for _, f := range strings.Fields(line) {
		if strings.EqualFold(f, mod) {
			return true
		}
	}
	return false
}

// ── Walker ──────────────────────────────────────────────────────────────────

type vbWalker struct {
	dir     string
	relFile string
	ns      []string
	types   []string // enclosing type names, innermost last
	out     []facts.Fact

	// An INDEX, not a pointer. w.out grows by append while a member body is being
	// walked, and append may move the backing array — a *facts.Fact taken before
	// that point would then address the old array and every relation added through
	// it would be silently discarded.
	member    int // index into out, or -1 between members
	loopDepth int
}

// scanVB walks one VB source file and returns its facts.
func scanVB(src, relFile string) []facts.Fact {
	rel := filepath.ToSlash(relFile)
	w := &vbWalker{dir: path.Dir(rel), relFile: rel, member: -1}

	for _, ln := range vbLogicalLines(src) {
		w.line(ln)
	}
	return w.out
}

func (w *vbWalker) typeName() string {
	if len(w.types) == 0 {
		return ""
	}
	return w.dir + "." + strings.Join(w.types, ".")
}

func (w *vbWalker) namespace() string { return strings.Join(w.ns, ".") }

// cur returns the fact new relations attach to: the member being walked, or the
// enclosing type when between members (a field initializer, an Inherits clause).
func (w *vbWalker) cur() *facts.Fact {
	if w.member >= 0 {
		return &w.out[w.member]
	}
	for i := len(w.out) - 1; i >= 0; i-- {
		if w.out[i].Kind == facts.KindSymbol && w.out[i].Name == w.typeName() {
			return &w.out[i]
		}
	}
	return nil
}

func (w *vbWalker) addRel(kind, target string) {
	f := w.cur()
	if f == nil || target == "" || target == f.Name {
		return
	}
	for _, r := range f.Relations {
		if r.Kind == kind && r.Target == target {
			return
		}
	}
	f.Relations = append(f.Relations, facts.Relation{Kind: kind, Target: target})
}

func (w *vbWalker) line(ln vbLine) {
	t := ln.text

	switch {
	case vbNamespace.MatchString(t):
		w.ns = append(w.ns, vbNamespace.FindStringSubmatch(t)[1])
		return
	case vbEndNS.MatchString(t):
		if len(w.ns) > 0 {
			w.ns = w.ns[:len(w.ns)-1]
		}
		return
	case vbEndType.MatchString(t):
		w.closeMember()
		if len(w.types) > 0 {
			w.types = w.types[:len(w.types)-1]
		}
		return
	case vbEndMethod.MatchString(t):
		w.closeMember()
		return
	}

	if m := vbImports.FindStringSubmatch(t); m != nil {
		w.emitImport(m[1], m[2], ln.line)
		return
	}
	if m := vbType.FindStringSubmatch(t); m != nil {
		w.openType(m[1], m[2], t, ln.line)
		return
	}
	if m := vbDelegate.FindStringSubmatch(t); m != nil {
		w.emitType("delegate", m[1], t, ln.line)
		return
	}
	if m := vbInherits.FindStringSubmatch(t); m != nil {
		for _, s := range vbTypeList(m[1]) {
			w.addRel(facts.RelImplements, s)
		}
		return
	}
	if m := vbImplements.FindStringSubmatch(t); m != nil && w.member < 0 {
		for _, s := range vbTypeList(m[1]) {
			w.addRel(facts.RelImplements, s)
		}
		return
	}

	// Member declarations. A Sub/Function opens a body; a Property or Event may or
	// may not, and either way its own line can carry references.
	// `New` is a keyword everywhere except here, where it names the constructor.
	if m := vbMethod.FindStringSubmatch(t); m != nil &&
		(!vbIsKeyword(m[2]) || strings.EqualFold(m[2], "New")) {
		w.openMember(m[2], t, ln.line)
		w.bodyRefs(t)
		return
	}
	if m := vbProperty.FindStringSubmatch(t); m != nil && !vbIsKeyword(m[1]) {
		w.emitMember("property", m[1], t, ln.line)
		w.bodyRefs(t)
		return
	}
	if m := vbEvent.FindStringSubmatch(t); m != nil && !vbIsKeyword(m[1]) {
		w.emitMember("event", m[1], t, ln.line)
		return
	}

	// A field or constant, only when it is part of the public surface — private
	// state is not a node anyone traverses, the same rule the C# walker applies.
	if w.member < 0 && len(w.types) > 0 {
		if m := vbField.FindStringSubmatch(t); m != nil && !vbIsKeyword(m[1]) && vbExported(t) {
			kind := "variable"
			if vbHasModifier(t, "Const") {
				kind = "constant"
			}
			w.emitMember(kind, m[1], t, ln.line)
		}
	}

	w.bodyRefs(t)
}

// vbTypeList splits an Inherits/Implements clause, dropping generic arguments so
// `IEquatable(Of GlobalImport)` targets `IEquatable`.
func vbTypeList(s string) []string {
	var out []string
	depth := 0
	cur := strings.Builder{}
	flush := func() {
		v := strings.TrimSpace(cur.String())
		cur.Reset()
		if v == "" {
			return
		}
		if i := strings.Index(strings.ToLower(v), "(of "); i >= 0 {
			v = v[:i]
		}
		v = strings.TrimSpace(v)
		if i := strings.LastIndex(v, "."); i >= 0 {
			v = v[i+1:]
		}
		if v != "" && !vbIsKeyword(v) {
			out = append(out, v)
		}
	}
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '(':
			depth++
			cur.WriteByte(s[i])
		case ')':
			depth--
			cur.WriteByte(s[i])
		case ',':
			if depth == 0 {
				flush()
				continue
			}
			cur.WriteByte(s[i])
		default:
			cur.WriteByte(s[i])
		}
	}
	flush()
	return out
}

func (w *vbWalker) emitImport(alias, pathName string, line int) {
	props := map[string]any{
		"language": "vbnet",
		"import":   pathName,
		"source":   "external", // refined by classifyUsing once the repo is indexed
	}
	if alias != "" {
		props["alias"] = alias
	}
	w.out = append(w.out, facts.Fact{
		Kind:      facts.KindDependency,
		Name:      w.dir + " -> " + pathName,
		File:      w.relFile,
		Line:      line,
		Props:     props,
		Relations: []facts.Relation{{Kind: facts.RelImports, Target: pathName}},
	})
}

func (w *vbWalker) openType(keyword, name, decl string, line int) {
	w.closeMember()
	w.emitType(strings.ToLower(keyword), name, decl, line)
	w.types = append(w.types, name)
}

// vbSymbolKind maps a VB declaration keyword onto the shared symbol_kind
// vocabulary. `Module` is VB's static class — it has no C# keyword, and calling
// it a class is what puts it in the type index that resolves bare references.
func vbSymbolKind(keyword string) string {
	switch keyword {
	case "class", "module":
		return facts.SymbolClass
	case "interface":
		return facts.SymbolInterface
	case "structure":
		return facts.SymbolStruct
	case "enum":
		return facts.SymbolEnum
	default:
		return facts.SymbolType
	}
}

func (w *vbWalker) emitType(keyword, name, decl string, line int) {
	full := name
	if len(w.types) > 0 {
		full = strings.Join(w.types, ".") + "." + name
	}
	props := map[string]any{
		"language":    "vbnet",
		"symbol_kind": vbSymbolKind(keyword),
		"exported":    vbExported(decl),
	}
	if keyword == "module" {
		props["vb_module"] = true // a static class, not a namespace
	}
	if vbHasModifier(decl, "Partial") {
		props["partial"] = true
	}
	if ns := w.namespace(); ns != "" {
		props["namespace"] = ns
		props["fqn"] = ns + "." + full
	}
	w.out = append(w.out, facts.Fact{
		Kind:      facts.KindSymbol,
		Name:      w.dir + "." + full,
		File:      w.relFile,
		Line:      line,
		Props:     props,
		Relations: []facts.Relation{{Kind: facts.RelDeclares, Target: w.dir}},
	})
}

func (w *vbWalker) memberFact(kind, name, decl string, line int) facts.Fact {
	owner := w.typeName()
	full := w.dir + "." + name
	if owner != "" {
		full = owner + "." + name
	}
	props := map[string]any{
		"language":    "vbnet",
		"symbol_kind": kind,
		"exported":    vbExported(decl),
	}
	if owner != "" {
		props["receiver"] = owner
	}
	if vbHasModifier(decl, "Shared") {
		props["static"] = true
	}
	rels := []facts.Relation{{Kind: facts.RelDeclares, Target: w.dir}}
	// `Implements IFoo.Bar` and `Handles ctl.Event` on a member line are both real
	// references: the first to the interface member it satisfies, the second to the
	// event it subscribes to. Without Handles, a WinForms handler that nothing calls
	// by name reads as dead.
	if m := vbMemberImplements.FindStringSubmatch(decl); m != nil {
		for _, s := range vbTypeList(m[1]) {
			rels = append(rels, facts.Relation{Kind: facts.RelImplements, Target: s})
		}
	}
	if m := vbHandles.FindStringSubmatch(decl); m != nil {
		for _, s := range strings.Split(m[1], ",") {
			s = strings.TrimSpace(s)
			if i := strings.LastIndex(s, "."); i >= 0 {
				s = s[i+1:]
			}
			if s != "" && !vbIsKeyword(s) {
				rels = append(rels, facts.Relation{Kind: facts.RelCalls, Target: s})
			}
		}
	}
	return facts.Fact{
		Kind:      facts.KindSymbol,
		Name:      full,
		File:      w.relFile,
		Line:      line,
		Props:     props,
		Relations: rels,
	}
}

func (w *vbWalker) emitMember(kind, name, decl string, line int) {
	w.out = append(w.out, w.memberFact(kind, name, decl, line))
}

func (w *vbWalker) openMember(name, decl string, line int) {
	w.closeMember()
	kind := facts.SymbolMethod
	if strings.EqualFold(name, "New") {
		kind = "constructor"
	}
	f := w.memberFact(kind, name, decl, line)
	f.SetProp("cyclomatic", 1)
	w.out = append(w.out, f)
	w.member = len(w.out) - 1
	w.loopDepth = 0
}

func (w *vbWalker) closeMember() {
	w.member = -1
	w.loopDepth = 0
}

// bodyRefs harvests the references and complexity signals on one line.
func (w *vbWalker) bodyRefs(t string) {
	f := w.cur()
	if f == nil {
		return
	}

	if w.member >= 0 {
		mp := w.out[w.member].Props
		if n := len(vbDecision.FindAllString(t, -1)); n > 0 {
			if c, ok := mp["cyclomatic"].(int); ok {
				mp["cyclomatic"] = c + n
			}
		}
		if vbLoop.MatchString(t) {
			w.loopDepth++
			if d, _ := mp["loop_depth"].(int); w.loopDepth > d {
				mp["loop_depth"] = w.loopDepth
			}
			c, _ := mp["loop_count"].(int)
			mp["loop_count"] = c + 1
		}
		if vbEndLoop.MatchString(t) && w.loopDepth > 0 {
			w.loopDepth--
		}
	}

	for _, m := range vbNew.FindAllStringSubmatch(t, -1) {
		name := m[1]
		if i := strings.LastIndex(name, "."); i >= 0 {
			name = name[i+1:]
		}
		if !vbIsKeyword(name) {
			w.addRel(facts.RelInstantiates, name)
			if ioConstructedTypes[name] {
				w.markIO()
			}
		}
	}
	for _, m := range vbQualified.FindAllStringSubmatch(t, -1) {
		recv, member := m[1], m[2]
		if vbIsKeyword(recv) || vbIsKeyword(member) {
			continue
		}
		w.addRel(facts.RelCalls, member)
		w.addRel(facts.RelCalls, recv)
		if ioStaticTypes[recv] || ioMethods[member] {
			w.markIO()
		}
	}
	for _, m := range vbCall.FindAllStringSubmatch(t, -1) {
		if name := m[1]; !vbIsKeyword(name) {
			w.addRel(facts.RelCalls, name)
			if ioMethods[name] {
				w.markIO()
			}
		}
	}
	for _, m := range vbMemberRef.FindAllStringSubmatch(t, -1) {
		if name := m[1]; !vbIsKeyword(name) {
			w.addRel(facts.RelCalls, name)
			if ioMethods[name] {
				w.markIO()
			}
		}
	}
}

func (w *vbWalker) markIO() {
	if w.member >= 0 {
		w.out[w.member].SetProp("io_direct", true)
	}
}
