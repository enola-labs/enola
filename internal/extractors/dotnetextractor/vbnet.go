package dotnetextractor

// VB.NET — the other language that compiles to the same assemblies.
//
// Line-oriented rather than AST-driven, and that is a property of the language
// rather than a shortcut. VB terminates every construct with an explicit `End
// Class` / `End Sub`, has no braces and no expression-level ambiguity about where
// a declaration begins, so a scanner with a container stack recovers the same
// structure a parser would. (There is also no maintained tree-sitter grammar for
// it, and the vendored runtime caps at ABI 14 — see the package doc.)
//
// The measured problem: dotnet/roslyn's VB compiler is 3,652 `.vb` files, and
// 11,589 of the repository's orphans are C# symbols whose only callers live in
// them — the single largest false-positive block in the .NET corpus, larger than
// any markup format.
//
// VB is CASE-INSENSITIVE. Every keyword match here folds case; a repository that
// writes `imports` or `end sub` is legal VB and parses the same.

import (
	"path"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/enola-labs/enola/internal/facts"
)

func isVBFile(relFile string) bool {
	return strings.EqualFold(filepath.Ext(relFile), ".vb")
}

// vbGeneratedSuffixes mirror generatedSuffixes for VB's own conventions.
var vbGeneratedSuffixes = []string{".designer.vb", ".generated.vb", ".g.vb"}

func isGeneratedVB(relFile string, src string) bool {
	base := strings.ToLower(path.Base(filepath.ToSlash(relFile)))
	for _, suf := range vbGeneratedSuffixes {
		if strings.HasSuffix(base, suf) {
			return true
		}
	}
	// `My Project/` is the VB project-system folder: AssemblyInfo, Resources and
	// Settings designers, all generated.
	if strings.Contains(filepath.ToSlash(relFile), "/My Project/") {
		return true
	}
	probe := src
	if len(probe) > autoGeneratedProbe {
		probe = probe[:autoGeneratedProbe]
	}
	return strings.Contains(probe, string(autoGeneratedMarker))
}

// ── Line preparation ────────────────────────────────────────────────────────

// vbStripComment removes a `'` comment, respecting string literals. VB has no
// escape character inside a string — `""` is an embedded quote — so a simple
// in-string toggle is exact rather than approximate.
func vbStripComment(line string) string {
	inStr := false
	for i := 0; i < len(line); i++ {
		switch line[i] {
		case '"':
			inStr = !inStr
		case '\'':
			if !inStr {
				return line[:i]
			}
		}
	}
	return line
}

// vbJoinContinuations folds VB's ` _` line continuation and the implicit
// continuation left by a trailing comma, so a declaration split across lines is
// scanned as the one statement it is. Roslyn's own VB writes multi-line parameter
// lists constantly.
//
// Returns one entry per logical line, carrying the 1-based line where it started.
type vbLine struct {
	text string
	line int
}

func vbLogicalLines(src string) []vbLine {
	raw := strings.Split(src, "\n")
	out := make([]vbLine, 0, len(raw))
	for i := 0; i < len(raw); i++ {
		text := strings.TrimRight(vbStripComment(raw[i]), " \t\r")
		start := i + 1
		for strings.HasSuffix(text, " _") || strings.HasSuffix(text, ",") {
			if i+1 >= len(raw) {
				break
			}
			i++
			text = strings.TrimSuffix(text, "_")
			text = strings.TrimRight(text, " \t\r") + " " +
				strings.TrimSpace(vbStripComment(raw[i]))
			text = strings.TrimRight(text, " \t\r")
		}
		if s := strings.TrimSpace(text); s != "" {
			out = append(out, vbLine{text: s, line: start})
		}
	}
	return out
}

// ── Declaration patterns ────────────────────────────────────────────────────

// VB modifiers that may precede a declaration. Matched case-insensitively.
const vbModifiers = `(?:(?:Public|Private|Friend|Protected|Partial|Shared|Shadows|` +
	`MustInherit|NotInheritable|MustOverride|Overridable|Overrides|Overloads|` +
	`ReadOnly|WriteOnly|Default|Narrowing|Widening|Iterator|Async|Custom|Static|` +
	`Const|Dim|WithEvents|NotOverridable)\s+)*`

var (
	vbNamespace = regexp.MustCompile(`(?i)^Namespace\s+([\w.]+)`)
	vbEndNS     = regexp.MustCompile(`(?i)^End\s+Namespace\b`)

	vbType = regexp.MustCompile(`(?i)^` + vbModifiers +
		`(Class|Module|Structure|Interface|Enum)\s+([A-Za-z_]\w*)`)
	vbEndType = regexp.MustCompile(`(?i)^End\s+(Class|Module|Structure|Interface|Enum)\b`)

	vbDelegate = regexp.MustCompile(`(?i)^` + vbModifiers +
		`Delegate\s+(?:Sub|Function)\s+([A-Za-z_]\w*)`)

	vbMethod = regexp.MustCompile(`(?i)^` + vbModifiers +
		`(Sub|Function)\s+([A-Za-z_]\w*)`)
	vbEndMethod = regexp.MustCompile(`(?i)^End\s+(Sub|Function)\b`)

	vbProperty = regexp.MustCompile(`(?i)^` + vbModifiers + `Property\s+([A-Za-z_]\w*)`)
	vbEvent    = regexp.MustCompile(`(?i)^` + vbModifiers + `Event\s+([A-Za-z_]\w*)`)

	vbField = regexp.MustCompile(`(?i)^` + vbModifiers + `([A-Za-z_]\w*)\s+As\s+`)

	vbImports = regexp.MustCompile(`(?i)^Imports\s+(?:([A-Za-z_]\w*)\s*=\s*)?([\w.]+(?:\(Of\s+[\w.,\s]+\))?)`)

	vbInherits   = regexp.MustCompile(`(?i)^Inherits\s+(.+)$`)
	vbImplements = regexp.MustCompile(`(?i)^Implements\s+(.+)$`)

	// `... Implements IEquatable(Of X).Equals` on a member line.
	vbMemberImplements = regexp.MustCompile(`(?i)\bImplements\s+([\w.(), ]+)$`)
	// `... Handles button.Click` wires an event to a handler.
	vbHandles = regexp.MustCompile(`(?i)\bHandles\s+([\w.,\s]+)$`)

	vbNew       = regexp.MustCompile(`(?i)\bNew\s+([A-Za-z_][\w.]*)`)
	vbCall      = regexp.MustCompile(`\b([A-Za-z_]\w*)\s*\(`)
	vbMemberRef = regexp.MustCompile(`\.([A-Za-z_]\w*)`)
	vbQualified = regexp.MustCompile(`\b([A-Z]\w*)\.([A-Za-z_]\w*)`)

	vbDecision = regexp.MustCompile(`(?i)(^|\s)(If|ElseIf|For|While|Case|Catch)\b|\bAndAlso\b|\bOrElse\b`)
	vbLoop     = regexp.MustCompile(`(?i)^(For|While|Do)\b`)
	vbEndLoop  = regexp.MustCompile(`(?i)^(Next|Loop)\b`)
)

