package dotnetextractor

import (
	"strings"

	"github.com/enola-labs/enola/internal/extractors/tsutil"
	"github.com/enola-labs/enola/internal/facts"
	sitter "github.com/tree-sitter/go-tree-sitter"
)

// csharpDoc returns the doc prop of a declaration: the <summary> of its `///` XML
// doc comment, or the run of `//` lines or the `/** */` block above it. Attributes
// are part of the declaration's node, so the comment above them is its sibling.
func csharpDoc(n *sitter.Node, src []byte) string {
	comments := tsutil.PrecedingComments(n, src, kindOf, func(k string) bool { return k == "comment" })
	var xml []string
	for _, c := range comments {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(c), "///"); ok {
			xml = append(xml, rest)
		} else {
			xml = nil // the XML comment is the run directly above the declaration
		}
	}
	if len(xml) > 0 {
		return facts.DocText(tsutil.XMLDocSummary(strings.Join(xml, "\n")))
	}
	return facts.DocText(tsutil.DocCommentText(comments, []string{"//"}, func(line string) bool {
		return strings.HasPrefix(line, "ReSharper") || strings.HasPrefix(line, "<auto-generated")
	}))
}
