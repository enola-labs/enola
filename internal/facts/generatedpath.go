package facts

import (
	"strings"

	"github.com/enola-labs/enola/internal/factpath"
)

// DartGeneratedSuffixes are the file-name conventions of Dart code generators.
//
// This is the single list. The Dart extractor skips these files, config.Default()
// derives its walker ignore globs from it, and the generated-path check behind the
// dead-code and performance passes reads it. Three copies of it had drifted apart:
// a suffix the walker does not ignore but the extractor skips leaves the file in the
// shared cache partition, so regenerating it invalidates every extractor's cache.
//
// A suffix belongs here when a generator owns the name. A banner is not enough on
// its own: drift_dev's make-migrations output (`.steps.dart`) puts its
// "GENERATED BY drift_dev" banner after the imports, where a leading-comment scan
// never reaches it.
var DartGeneratedSuffixes = []string{
	".g.dart",       // build_runner: json_serializable, drift, retrofit, injectable
	".freezed.dart", // freezed: immutable data classes
	".mocks.dart",   // mockito
	".gr.dart",      // auto_route
	".config.dart",  // injectable
	".gform.dart",   // reactive_forms
	".steps.dart",   // drift_dev make-migrations: step-by-step schema versions
	".pb.dart",      // protoc-gen-dart
	".pbenum.dart",
	".pbjson.dart",
	".pbserver.dart",
	".pbgrpc.dart",
}

// IsGeneratedDartPath reports whether a path's file name carries a Dart code
// generator's suffix. The match is on the suffix of the base name, case-insensitive,
// so `lib/config.dart` or `lib/steps.dart` stay source.
func IsGeneratedDartPath(p string) bool {
	base := strings.ToLower(factpath.Base(p))
	for _, suf := range DartGeneratedSuffixes {
		if strings.HasSuffix(base, suf) {
			return true
		}
	}
	return false
}
